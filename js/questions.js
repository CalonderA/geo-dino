  /* Банк вопросов: случайный порядок без повторов
     до завершения полного круга. */

  function QuestionBank(list) {
    if (!Array.isArray(list) || list.length === 0) {
      throw new Error('База вопросов должна содержать хотя бы один вопрос.');
    }

    this.list = list.slice();
    this.order = [];
    this.pos = 0;
    this.lastIndex = -1;

    this._reshuffle();
  }

  QuestionBank.prototype._reshuffle = function () {
    var order = [];

    for (var i = 0; i < this.list.length; i++) {
      order.push(i);
    }

    // Алгоритм Фишера — Йетса.
    for (var j = order.length - 1; j > 0; j--) {
      var k = Math.floor(Math.random() * (j + 1));
      var t = order[j];

      order[j] = order[k];
      order[k] = t;
    }

    // Не повторяем последний вопрос в начале нового круга.
    if (order.length > 1 && order[0] === this.lastIndex) {
      var tmp = order[0];
      order[0] = order[1];
      order[1] = tmp;
    }

    this.order = order;
    this.pos = 0;
  };

  QuestionBank.prototype.next = function () {
    if (this.pos >= this.order.length) {
      this._reshuffle();
    }

    var questionIndex = this.order[this.pos];
    var item = this.list[questionIndex];

    this.lastIndex = questionIndex;
    this.pos++;

    // Перемешиваем ответы вместе с исходными индексами.
    var options = item.options.map(function (text, idx) {
      return {
        text: text,
        idx: idx
      };
    });

    for (var j = options.length - 1; j > 0; j--) {
      var k = Math.floor(Math.random() * (j + 1));
      var t = options[j];

      options[j] = options[k];
      options[k] = t;
    }

    // Находим новый индекс правильного ответа.
    var correctIdx = options.findIndex(function (option) {
      return option.idx === item.correct;
    });

    if (correctIdx === -1) {
      throw new Error('У вопроса указан неверный индекс правильного ответа: ' + item.q);
    }

    return {
      tag: item.tag,
      q: item.q,
      options: options.map(function (option) {
        return option.text;
      }),
      correct: correctIdx
    };
  };

